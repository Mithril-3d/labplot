def clean_accelerator(text):
    """&File などのアクセラレータ記号を取り出す"""
    accel = None
    m = re.search(r'&([A-Za-z0-9])', text)
    if m:
        accel = m.group(1)
    clean_text = text.replace('&', '')
    return clean_text, accel

def apply_accelerator(translated_text, accel):
    """日本語訳に (&F) などのアクセラレータキーを付与する"""
    if not accel:
        return translated_text
    # すでに (&X) が入っている場合はスキップ
    if f"(&{accel})" in translated_text or f"&{accel}" in translated_text:
        return translated_text
    return f"{translated_text}(&{accel})"
